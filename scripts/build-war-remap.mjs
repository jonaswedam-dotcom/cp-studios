// One-off helper for migration 037 (remap old admin-1 holdings onto the country-quarter map).
// Builds a lookup: old adm1_code (the region_id values still stored in war_regions) -> the new
// `<ADM0_A3>_<Q>` quarter id. Each old province is assigned to the quarter OF ITS OWN COUNTRY
// whose centroid is nearest — so the target id always exists on the deployed map (no orphans)
// and the province lands in the correct NW/NE/SW/SE quadrant.
//
// The old asset is no longer in the repo; recover it from the commit before the quarter rebuild:
//   git show 24061aa~1:public/war/provinces.json > /tmp/old-provinces.json
//
// Usage: node scripts/build-war-remap.mjs [oldProvincesJson] [newProvincesJson]
// Emits: /tmp/remap-values.sql  (the VALUES rows embedded into migration 037)
import { readFileSync, writeFileSync } from 'node:fs'

const OLD = process.argv[2] || '/tmp/old-provinces.json'
const NEW = process.argv[3] || 'public/war/provinces.json'

const oldRegions = JSON.parse(readFileSync(OLD, 'utf8')).regions
const newRegions = JSON.parse(readFileSync(NEW, 'utf8')).regions

const norm = (s) => (s || '').toString().trim().toLowerCase()
function distKm([lng1, lat1], [lng2, lat2]) {
  const R = 6371, toRad = (d) => (d * Math.PI) / 180
  const dLat = toRad(lat2 - lat1), dLng = toRad(lng2 - lng1)
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2
  return 2 * R * Math.asin(Math.min(1, Math.sqrt(a)))
}

// Index new quarters by country-code prefix (FRA_NW -> FRA) and by country name (fallback).
const byCode = new Map(), byName = new Map()
for (const [id, r] of Object.entries(newRegions)) {
  const code = id.slice(0, id.lastIndexOf('_'))
  if (!byCode.has(code)) byCode.set(code, [])
  byCode.get(code).push({ id, c: r.centroid })
  const n = norm(r.country)
  if (!byName.has(n)) byName.set(n, [])
  byName.get(n).push({ id, c: r.centroid })
}

let viaCode = 0, viaName = 0
const unmapped = []
const pairs = []
for (const [id, r] of Object.entries(oldRegions)) {
  const code = id.split('-')[0]
  let cand = byCode.get(code), how = 'code'
  if (!cand || !cand.length) { cand = byName.get(norm(r.country)); how = 'name' }
  if (!cand || !cand.length) { unmapped.push({ id, country: r.country }); continue }
  let best = null, bd = Infinity
  for (const q of cand) { const d = distKm(r.centroid, q.c); if (d < bd) { bd = d; best = q } }
  pairs.push([id, best.id])
  how === 'code' ? viaCode++ : viaName++
}

console.error(`old provinces:     ${Object.keys(oldRegions).length}`)
console.error(`new quarters:      ${Object.keys(newRegions).length}`)
console.error(`mapped:            ${pairs.length} (via code ${viaCode}, via name ${viaName})`)
console.error(`unmapped (dropped):${unmapped.length}`)
console.error('unmapped sample:', unmapped.slice(0, 25))
// Spot-checks: a province should map to a quarter of the same country.
for (const probe of ['ARG-1309', 'USA-3514', 'FRA-2310', 'RUS-2394', 'AUS-2650']) {
  const hit = pairs.find(([a]) => a === probe)
  console.error(`  ${probe} -> ${hit ? hit[1] : '(not found / unmapped)'}`)
}

const values = pairs.map(([a, b]) => `('${a.replace(/'/g, "''")}','${b}')`).join(',\n  ')

// Assemble the full, self-contained migration (the 4.5k-row VALUES block is generated, not hand-typed).
const migration = `-- ============================================================
-- 037 – Restore CP War holdings onto the country-quarter map (CP War 3.0).
--
-- GENERATED by scripts/build-war-remap.mjs — do not hand-edit the VALUES block.
-- Run by hand in the Supabase SQL editor, in numerical order, AFTER 036.
--
-- !!  DO NOT RUN 035_war_map_reset.sql (now disabled). That TRUNCATEs the board;
--     this migration RESTORES it, by moving every owned region from its old admin-1
--     id (e.g. 'ARG-1309') to the country-quarter that contains it ('ARG_NE').
--
-- Behaviour:
--   * Provinces that collapse into one quarter merge; the owner's units are summed.
--   * If two players land on the same quarter, the one with more provinces there wins
--     (tie: more units); the loser's units on that quarter are forfeited.
--   * Buildings follow their region (deduped per type, highest level kept).
--   * In-flight movements and the event feed are cleared (they referenced dead ids).
--   * Each player keeps exactly one HQ; spawn_region is repointed to it.
--   * No accounts are deleted.
--
-- Mapping: ${pairs.length} of ${Object.keys(oldRegions).length} old provinces (${unmapped.length} disputed/uninhabited
-- territories with no quarter are dropped). See scripts/build-war-remap.mjs.
--
-- SAFE DRY-RUN: the whole thing is one transaction ending in COMMIT. To preview WITHOUT
-- applying, change the final \`commit;\` to \`rollback;\` and run — the per-player BEFORE->AFTER
-- table prints either way. If it looks right, set it back to \`commit;\` and run again.
-- (A SQL error anywhere also rolls the whole thing back — nothing is half-applied.)
-- ============================================================
begin;

create temporary table _remap (old_id text primary key, new_id text not null) on commit drop;
insert into _remap (old_id, new_id) values
  ${values};

-- BEFORE snapshot (for the preview at the end)
create temporary table _before on commit drop as
  select owner_id, max(owner_name) owner_name, count(*) provinces,
         sum(soldier+tank+jet+warship) units
  from public.war_regions where owner_id is not null group by owner_id;

-- 1) every OWNED old-id region, translated to its target quarter
create temporary table _owned on commit drop as
  select m.new_id as quarter_id, r.owner_id, r.owner_name, r.color, r.is_hq,
         r.soldier, r.tank, r.jet, r.warship
  from public.war_regions r
  join _remap m on m.old_id = r.region_id
  where r.owner_id is not null;

-- 2) winning owner per target quarter: most provinces there, tie -> most units
create temporary table _winner on commit drop as
  select distinct on (quarter_id) quarter_id, owner_id, owner_name, color
  from (
    select quarter_id, owner_id, owner_name, color,
           count(*) prov, sum(soldier+tank+jet+warship) units
    from _owned group by quarter_id, owner_id, owner_name, color
  ) g
  order by quarter_id, prov desc, units desc, owner_id;

-- 3) winner's summed units (+ inherited HQ flag) per quarter
create temporary table _final on commit drop as
  select w.quarter_id, w.owner_id, w.owner_name, w.color,
         split_part(w.quarter_id, '_', 1) as country_code,
         sum(o.soldier) soldier, sum(o.tank) tank, sum(o.jet) jet, sum(o.warship) warship,
         bool_or(o.is_hq) had_hq
  from _winner w
  join _owned o on o.quarter_id = w.quarter_id and o.owner_id = w.owner_id
  group by w.quarter_id, w.owner_id, w.owner_name, w.color;

-- 4) buildings to carry over: only those whose owner wins the target quarter;
--    dedupe (quarter,type) keeping the highest level (mirrors migration 029)
create temporary table _bld on commit drop as
  select distinct on (f.quarter_id, b.type)
         f.quarter_id as region_id, b.owner_id, b.type, b.level
  from public.war_buildings b
  join _remap m on m.old_id = b.region_id
  join _final f on f.quarter_id = m.new_id and f.owner_id = b.owner_id
  order by f.quarter_id, b.type, b.level desc;

-- 5) clear transient state that referenced dead ids
delete from public.war_movements;
delete from public.war_events;

-- 6) drop all old admin-1 region rows AND any existing rows on quarters we're rebuilding
--    (buildings on these cascade-delete; that is why _bld was captured first)
delete from public.war_regions
  where region_id in (select old_id from _remap)
     or region_id in (select quarter_id from _final);

-- 7) insert the rebuilt quarter ownership (HQ set in step 9)
insert into public.war_regions
  (region_id, country_code, owner_id, owner_name, color, is_hq, soldier, tank, jet, warship, updated_at)
select quarter_id, country_code, owner_id, owner_name, color, false, soldier, tank, jet, warship, now()
from _final;

-- 8) re-insert carried-over buildings
insert into public.war_buildings (region_id, owner_id, type, level, created_at)
select region_id, owner_id, type, level, now() from _bld;

-- 9) exactly one HQ per player: prefer an inherited HQ, else the quarter with most units
with ranked as (
  select quarter_id, owner_id,
         row_number() over (partition by owner_id
           order by had_hq desc, (soldier+tank+jet+warship) desc, quarter_id) rn
  from _final
)
update public.war_regions r set is_hq = true
  from ranked
  where ranked.rn = 1 and ranked.quarter_id = r.region_id and ranked.owner_id = r.owner_id;

-- 10) repoint each player's spawn_region to their new HQ
update public.war_players p set spawn_region = r.region_id
  from public.war_regions r
  where r.owner_id = p.user_id and r.is_hq = true;

-- 11) PREVIEW — per player: holdings before (old provinces) vs after (quarters)
select coalesce(b.owner_name, a.owner_name) as player,
       coalesce(b.provinces, 0) as before_provinces,
       coalesce(a.quarters, 0)  as after_quarters,
       coalesce(b.units, 0)     as before_units,
       coalesce(a.units, 0)     as after_units
from _before b
full outer join (
  select owner_id, max(owner_name) owner_name, count(*) quarters,
         sum(soldier+tank+jet+warship) units
  from public.war_regions where owner_id is not null group by owner_id
) a on a.owner_id = b.owner_id
order by after_quarters desc;

-- DRY-RUN: change to \`rollback;\` to preview without applying. APPLY: keep \`commit;\`.
commit;
`

const MIG = 'supabase/migrations/037_war_remap_to_quarters.sql'
writeFileSync('/tmp/remap-values.sql', values)
writeFileSync(MIG, migration)
console.error(`\nwrote /tmp/remap-values.sql (${pairs.length} rows)`)
console.error(`wrote ${MIG} (${migration.length} bytes)`)
