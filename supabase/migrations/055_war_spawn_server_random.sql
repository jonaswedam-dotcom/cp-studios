-- ── 2) war_spawn: server picks a RANDOM unclaimed region (ignores p_region) ───
-- Signature unchanged so the deployed client keeps working; p_region/p_country are
-- now IGNORED — the server draws the region from the unclaimed pool. Mirrors the
-- 047 body (1h shield) otherwise. Race-safe: re-checks ownership after the claim.
create or replace function public.war_spawn(p_region text, p_country text, p_color text, p_name text)
returns text language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); existing text; v_region text; v_country text;
begin
  if uid is null then raise exception 'not authenticated'; end if;
  -- idempotent: already enrolled -> return existing spawn
  select spawn_region into existing from public.war_players where user_id = uid;
  if existing is not null then return existing; end if;

  -- SERVER-CHOSEN random spawn from the unclaimed pool (anti "place yourself anywhere")
  select p.region_id, p.country into v_region, v_country
  from public.war_region_pool p
  where not exists (
    select 1 from public.war_regions r where r.region_id = p.region_id and r.owner_id is not null
  )
  order by random() limit 1;
  if v_region is null then raise exception 'world full'; end if;

  insert into public.war_players (user_id, display_name, color, spawn_region, shield_until, last_income_at, last_active_at)
  values (uid, p_name, p_color, v_region, now() + interval '1 hour', now(), now())
  on conflict (user_id) do nothing;
  insert into public.war_regions (region_id, country_code, owner_id, owner_name, color, is_hq, soldier, tank, jet, warship, updated_at)
  values (v_region, v_country, uid, p_name, p_color, true, 500, 0, 0, 0, now())
  on conflict (region_id) do update
    set owner_id = excluded.owner_id, owner_name = excluded.owner_name, color = excluded.color,
        is_hq = true, soldier = 500, updated_at = now()
    where public.war_regions.owner_id is null;
  -- lost a concurrent race for v_region? roll back the player insert too.
  if not exists (select 1 from public.war_regions where region_id = v_region and owner_id = uid) then
    raise exception 'spawn race, retry';
  end if;
  return v_region;
end;
$$;
revoke all on function public.war_spawn(text,text,text,text) from public;
grant execute on function public.war_spawn(text,text,text,text) to authenticated;

-- ── 3) war_buy_units: same anti-place-anywhere fix on the RESPAWN branch ──────
-- Faithful copy of the migration 052 body; the ONLY change is that respawn no longer
-- trusts p_region — the server draws a random unclaimed region (v_target). The normal
-- branch still targets the province you own (p_region). 055 applies after 052, so this
-- definition wins. Constants stay in sync with src/war/{units,economy,buildings}.js.
create or replace function public.war_buy_units(p_region text, p_type text, p_count integer)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  uid         uuid := auth.uid();
  v_unit_cost integer;
  v_strength  numeric;
  v_factory   integer;
  v_army_mult numeric;
  v_cost_mult numeric;
  v_cost      numeric;   -- numeric (not int): absurd orders overflow int4 before the
                          -- 'insufficient coins' check; balance>=v_cost keeps it in range.
  v_owned     integer;
  v_balance   integer;
  v_name      text;
  v_color     text;
  v_target    text;
begin
  if uid is null then raise exception 'not authenticated'; end if;
  if p_count is null or p_count < 1 then raise exception 'invalid count'; end if;
  if p_type not in ('soldier','tank','jet','warship') then raise exception 'invalid unit type'; end if;

  v_unit_cost := case p_type when 'soldier' then 100 when 'tank' then 400 when 'jet' then 800 when 'warship' then 4000 end;

  select coalesce(sum(soldier * 1 + tank * 5 + jet * 3 + warship * 20), 0)
    into v_strength from public.war_regions where owner_id = uid;
  v_army_mult := 1 + 0.25 * floor(v_strength / 2500);

  select coalesce(sum(level), 0) into v_factory from public.war_buildings where owner_id = uid and type = 'factory';
  v_cost_mult := greatest(0.5, 1 - 0.1 * v_factory);

  v_cost := round((v_unit_cost::numeric * p_count) * v_cost_mult * v_army_mult);

  select count(*) into v_owned from public.war_regions where owner_id = uid;

  if v_owned = 0 then
    -- respawn: SERVER picks the region (anti "place yourself anywhere"). p_region ignored.
    if p_type = 'warship' then raise exception 'warships require a port'; end if;
    select p.region_id into v_target
    from public.war_region_pool p
    where not exists (select 1 from public.war_regions r where r.region_id = p.region_id and r.owner_id is not null)
    order by random() limit 1;
    if v_target is null then raise exception 'world full'; end if;
    select display_name, color into v_name, v_color from public.war_players where user_id = uid;
  else
    v_target := p_region;
    if not exists (select 1 from public.war_regions where region_id = v_target and owner_id = uid for update) then
      raise exception 'you do not own this province';
    end if;
    if p_type = 'warship' and not exists (
      select 1 from public.war_buildings where region_id = v_target and owner_id = uid and type = 'port'
    ) then raise exception 'warships require a port in this province'; end if;
  end if;

  update public.wallets set balance = balance - v_cost
    where user_id = uid and balance >= v_cost
    returning balance into v_balance;
  if not found then raise exception 'insufficient coins'; end if;

  if v_owned = 0 then
    insert into public.war_regions (region_id, owner_id, owner_name, color, is_hq, soldier, tank, jet, warship, updated_at)
    values (v_target, uid, v_name, v_color, true, 0, 0, 0, 0, now())
    on conflict (region_id) do update
      set owner_id = excluded.owner_id, owner_name = excluded.owner_name, color = excluded.color,
          is_hq = true, soldier = 0, tank = 0, jet = 0, warship = 0, updated_at = now()
      where public.war_regions.owner_id is null;
    if not exists (select 1 from public.war_regions where region_id = v_target and owner_id = uid) then
      raise exception 'region taken';
    end if;
  end if;

  update public.war_regions set
    soldier = soldier + (case when p_type = 'soldier' then p_count else 0 end),
    tank    = tank    + (case when p_type = 'tank'    then p_count else 0 end),
    jet     = jet     + (case when p_type = 'jet'     then p_count else 0 end),
    warship = warship + (case when p_type = 'warship' then p_count else 0 end),
    updated_at = now()
  where region_id = v_target and owner_id = uid;

  return jsonb_build_object('balance', v_balance, 'region', v_target);
end; $$;
