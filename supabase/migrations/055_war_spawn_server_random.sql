-- Migration 055: server-authoritative RANDOM spawn. Idempotent.
-- ╔═══════════════════════════════════════════════════════════════════════════╗
-- ║  THE FIX: stop players "placing themselves anywhere" in CP War.               ║
-- ║                                                                              ║
-- ║  Until now the spawn REGION was chosen by the client and merely validated     ║
-- ║  server-side as "unclaimed" (war_spawn, migration 028/047; war_buy_units      ║
-- ║  respawn, migration 052). Randomness lived ONLY in the client (pickRandom-     ║
-- ║  Spawn). Because the anon key ships in the public bundle, anyone could call    ║
-- ║  war_spawn / war_buy_units with ANY unclaimed region_id and land exactly       ║
-- ║  where they wanted. This migration moves the random pick to the SERVER.        ║
-- ║                                                                              ║
-- ║  The province graph is a client asset and was not in the DB, so the server     ║
-- ║  had no region universe to pick from. We seed it here as war_region_pool      ║
-- ║  (generated from public/war/provinces.json — RE-SEED if the map changes).      ║
-- ╚═══════════════════════════════════════════════════════════════════════════╝

